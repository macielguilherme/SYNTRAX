const portugueseToEnglish = Object.fromEntries(Object.entries(englishToPortuguese).map(([english, portuguese]) => [portuguese, english]))

export function translateStaticText(text: string, language: Language): string {
  const dictionary = language === 'pt' ? englishToPortuguese : portugueseToEnglish
  const exact = dictionary[text]
  if (exact) return exact

  let translated = text
  if (language === 'pt') {
    translated = translated
      .replace(/(\d+) success criteria recorded\./g, '$1 critérios de sucesso registrados.')
      .replace(/External tests:/g, 'Testes externos:')
      .replace(/Not run/g, 'Não executados')
      .replace(/(\d+) tasks complete/g, '$1 tarefas concluídas')
      .replace(/(\d+) \/ (\d+) tasks verified/g, '$1 / $2 tarefas verificadas')
      .replace(/Depends on /g, 'Depende de ')
      .replace(/depends on previous step/g, 'depende da etapa anterior')
      .replace(/No runs yet/g, 'Nenhuma execução')
  } else {
    translated = translated
      .replace(/(\d+) critérios de sucesso registrados\./g, '$1 success criteria recorded.')
      .replace(/Testes externos:/g, 'External tests:')
      .replace(/Não executados/g, 'Not run')
      .replace(/(\d+) tarefas concluídas/g, '$1 tasks complete')
      .replace(/(\d+) \/ (\d+) tarefas verificadas/g, '$1 / $2 tasks verified')
      .replace(/Depende de /g, 'Depends on ')
      .replace(/depende da etapa anterior/g, 'depends on previous step')
      .replace(/Nenhuma execução/g, 'No runs yet')
  }
  return translated
}
